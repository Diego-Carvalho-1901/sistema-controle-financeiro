"""Testes das migrações do Alembic."""

from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy import inspect

from financeiro.banco.conexao import criar_engine

ALEMBIC_INI = Path(__file__).resolve().parents[1] / "alembic.ini"


def _config(url: str) -> Config:
    config = Config(ALEMBIC_INI)
    config.set_main_option("sqlalchemy.url", url)
    return config


def test_upgrade_cria_tabelas_e_downgrade_apaga(tmp_path):
    url = f"sqlite:///{tmp_path / 'teste.db'}"
    config = _config(url)

    command.upgrade(config, "head")
    tabelas = set(inspect(criar_engine(url)).get_table_names())
    command.downgrade(config, "base")
    restantes = set(inspect(criar_engine(url)).get_table_names())

    assert {"usuarios", "categorias", "lancamentos"} <= tabelas
    assert restantes == {"alembic_version"}


def test_migracoes_estao_em_dia_com_as_tabelas(tmp_path):
    """Falha se alguém mudar tabelas.py e esquecer de criar a migração."""
    config = _config(f"sqlite:///{tmp_path / 'teste.db'}")
    command.upgrade(config, "head")

    command.check(config)  # lança AutogenerateDiffsDetected se houver diferença
